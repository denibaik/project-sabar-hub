from typing import Protocol
from uuid import UUID
from .entities import Bot

class BotRepository(Protocol):
    def create(self, bot: Bot, token_hash: str) -> Bot: ...
    def get(self, bot_id: UUID) -> tuple[Bot, str] | None: ...
    def find_by_username(self, username: str) -> bool: ...
    def find_by_token_candidates(self) -> list[tuple[Bot, str]]: ...
    def list(self) -> list[Bot]: ...
    def save(self, bot: Bot) -> Bot: ...
    def delete(self, bot_id: UUID) -> bool: ...
